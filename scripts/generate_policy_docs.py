#!/usr/bin/env python3
"""Generate the policy schema reference and precedence pages from the normative spec.

``docs/policy/schema-reference.md`` is rendered from ``spec/guard-policy/v1alpha1/schema.json`` and
``docs/policy/precedence.md`` quotes the frozen precedence section of ``semantics.md`` verbatim. Edit
the spec, then run:

    python scripts/generate_policy_docs.py          # rewrite both pages
    python scripts/generate_policy_docs.py --check  # fail when a page is out of date
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "spec" / "guard-policy" / "v1alpha1"
DOCS = ROOT / "docs" / "policy"
PRECEDENCE_HEADING = "## Current runtime precedence (frozen)"
EXTENSION_PATTERN = "^x-[a-z0-9][a-z0-9.-]{0,62}$"
GENERATED_NOTICE = "<!-- Generated by scripts/generate_policy_docs.py from the spec. Edit the spec, not this file. -->"
_REFERENCE = re.compile(r"^#/\$defs/(?P<name>.+)$")


def _link(name: str) -> str:
    return f"[{name}](#{name.lower()})"


def _describe(schema: dict[str, object]) -> str:
    reference = schema.get("$ref")
    if isinstance(reference, str) and (match := _REFERENCE.match(reference)):
        return _link(match["name"])
    if "const" in schema:
        return f"`{json.dumps(schema['const'])}`"
    if "enum" in schema:
        return "one of " + ", ".join(f"`{value}`" for value in schema["enum"])  # type: ignore[union-attr]
    for key in ("oneOf", "anyOf"):
        if key in schema:
            return " or ".join(_describe(option) for option in schema[key])  # type: ignore[union-attr]
    kind = schema.get("type")
    label = "/".join(kind) if isinstance(kind, list) else str(kind or "any")
    if kind == "array" and isinstance(schema.get("items"), dict):
        label = f"array of {_describe(schema['items'])}"  # type: ignore[arg-type]
    limits = []
    for key, text in (
        ("minLength", "min length"),
        ("maxLength", "max length"),
        ("minimum", "min"),
        ("maximum", "max"),
        ("minItems", "min items"),
        ("maxItems", "max items"),
        ("maxProperties", "max properties"),
    ):
        if key in schema:
            limits.append(f"{text} {schema[key]}")
    if schema.get("uniqueItems"):
        limits.append("unique items")
    if "pattern" in schema:
        limits.append(f"pattern `{schema['pattern']}`")
    return label + (f" ({', '.join(limits)})" if limits else "")


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _render_object(name: str, schema: dict[str, object]) -> list[str]:
    lines = [f"## {name}", ""]
    if isinstance(schema.get("description"), str):
        lines += [str(schema["description"]), ""]
    properties = schema.get("properties")
    if isinstance(properties, dict):
        required = set(schema.get("required", []))  # type: ignore[arg-type]
        lines += ["| Field | Required | Type |", "| --- | --- | --- |"]
        for field, definition in properties.items():
            lines.append(f"| `{field}` | {'yes' if field in required else 'no'} | {_cell(_describe(definition))} |")
        lines.append("")
        if schema.get("additionalProperties") is False:
            extension = schema.get("patternProperties") and EXTENSION_PATTERN in schema["patternProperties"]  # type: ignore[operator]
            lines.append(
                "No other fields are allowed"
                + (f", except extension keys matching `{EXTENSION_PATTERN}`." if extension else ".")
            )
            lines.append("")
    else:
        lines += [_describe(schema), ""]
    return lines


def render_schema_reference() -> str:
    schema = json.loads((SPEC / "schema.json").read_text(encoding="utf-8"))
    lines = [
        GENERATED_NOTICE,
        "",
        "# GuardPolicy schema reference",
        "",
        f"{schema['description']} The authoritative source is "
        "[`schema.json`](../../spec/guard-policy/v1alpha1/schema.json); this page is generated from it.",
        "",
        "Add this line to the top of a policy file and your editor validates it as you type:",
        "",
        "```yaml",
        "# yaml-language-server: $schema=https://guard.hashgraphonline.com/schema/policy/v1alpha1",
        "```",
        "",
        "## Document",
        "",
        "| Field | Required | Type |",
        "| --- | --- | --- |",
    ]
    required = set(schema["required"])
    for field, definition in schema["properties"].items():
        lines.append(f"| `{field}` | {'yes' if field in required else 'no'} | {_cell(_describe(definition))} |")
    lines += ["", "No other top-level fields are allowed, except extension keys.", ""]
    for name, definition in schema["$defs"].items():
        lines += _render_object(name, definition)
    return "\n".join(lines).rstrip("\n") + "\n"


def precedence_excerpt() -> str:
    text = (SPEC / "semantics.md").read_text(encoding="utf-8")
    start = text.index(PRECEDENCE_HEADING)
    rest = text[start:]
    following = re.search(r"^## ", rest[len(PRECEDENCE_HEADING) :], re.MULTILINE)
    end = len(PRECEDENCE_HEADING) + following.start() if following else len(rest)
    return rest[:end].rstrip("\n")


def render_precedence() -> str:
    quoted = "\n".join(f"> {line}" if line else ">" for line in precedence_excerpt().splitlines())
    return f"""{GENERATED_NOTICE}

# How Guard picks between rules

When more than one rule matches an event, Guard decides which one wins. `hol-guard policy check` and
`hol-guard policy test` show you the winner and every rule that lost, with the reason.

## The frozen runtime contract

The text below is quoted from [`semantics.md`](../../spec/guard-policy/v1alpha1/semantics.md), the
normative specification. It is the contract the runtime keeps.

{quoted}

## Reading the explanation

`policy check --format json` lists one candidate per compiled row, in document order. A rule that names
several artifacts compiles to one row per artifact, so one rule id can appear more than once. Each candidate
has a state:

| State | Meaning |
| --- | --- |
| `selected` | This rule decided the event. |
| `outranked` | The rule matched and lost. The reason says why: `block_wins`, `more_specific_rule` or `tie`. |
| `unmatched` | The rule does not apply. The reason names the first field that failed. |
| `expired` | The rule matched but its lifetime had ended at the event time. |
| `not_enforced` | The rule matched but Guard does not enforce it for this kind of artifact. |

When two rules tie on effect and specificity, the decision is flagged `ambiguous` and both rule ids are
listed in `tiedRuleIds`. `policy test` reports a test that hits an ambiguous winner as `ambiguous` so you
can tighten a match until one rule clearly wins.

If more than 256 rules match one event, Guard blocks the event without naming a rule and
`matchLimitExceeded` is true.
"""


def pages() -> dict[Path, str]:
    return {
        DOCS / "schema-reference.md": render_schema_reference(),
        DOCS / "precedence.md": render_precedence(),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when a generated page is out of date")
    args = parser.parse_args(argv)
    stale = []
    for path, content in pages().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path.relative_to(ROOT) if path.is_relative_to(ROOT) else path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        print("Out of date: " + ", ".join(str(path) for path in stale), file=sys.stderr)
        print("Run python scripts/generate_policy_docs.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
