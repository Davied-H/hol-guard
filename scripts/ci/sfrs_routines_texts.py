def variant(**over: object) -> dict:
    result = copy.deepcopy(DEFAULT)
    for key, value in over.items():
        if isinstance(value, dict) and isinstance(result.get(key), dict):
            result[key].update(value)
        else:
            result[key] = value
    return result


